"""Проверка суждений: русское утверждение → спецификация FTS → приговор.

Что это
-------
Человек дописывает правило к существующему расчёту словами. Правила разбора
(без модели) переводят фразу в спецификацию FTS, настоящий компилятор её
компилирует и исполняет, детектор `fts-gate` ищет структурные дефекты вывода,
и ответ различает ТРИ исхода — а не два:

  1. ПРОВЕРЕНО И ВЕРНО — построено, скомпилировано, исполнено, сертифицировано;
  2. ПРОВЕРЕНО И НЕВЕРНО — построено, но упала названная проверка, и по
     возможности назван контрпример;
  3. НЕ УДАЛОСЬ ФОРМАЛИЗОВАТЬ — разбор отказался. Отдельный исход, а не
     разновидность второго: «не понял» и «понял, и это неверно» — разные
     утверждения, и склеивать их значит врать в обе стороны.

Три условия, без которых цифры ниже не относятся к делу
-------------------------------------------------------
1. Только НАД ОБЪЯВЛЕННОЙ СХЕМОЙ. Поля и их типы — вход, а не то, что
   восстанавливается из текста. Голое «если сумма больше 1000, скидка 10 %»
   без известных полей слой отклоняет, и правильно делает: без объявленного
   «сумма» это догадка о том, что такое сумма.
2. Отказ обязан оставаться дешёвым. На незнакомой формулировке система
   переспрашивает, а не выбирает правдоподобное. Ровно этим она платит за
   ноль тихих ошибок, и попытка сэкономить на отказе тратит именно их.
3. Граница печатается В КАЖДОМ ответе, включая зелёный. Проверена
   ВЫВОДИМОСТЬ следствия из посылки, истинность посылки не проверена и
   проверена быть не может: модели мира у системы нет.

Что измерено (1 161 замер, площадка digit-ml)
---------------------------------------------
* формализовано на незнакомых формулировках: 70,6 % на чистом holdout,
  97,7 % после починки двух системных дыр, найденных этим же holdout;
* ТИХИХ ОШИБОК НОЛЬ. Ни одного случая «построилось, компилятор принял, а
  означает не то». Меряется дифференциальным исполнением: разобранное и
  эталонное правило исполняет ОДИН И ТОТ ЖЕ интерпретатор на векторах,
  построенных из порогов обеих сторон;
* детектор логических ошибок: 1 698 из 1 698 испорченных утверждений пойманы,
  ложных отказов 0 на 394 чистых;
* медиана разбора около 1 мс.

Почему копия в дерево, а не зависимость
---------------------------------------
Оригинал живёт в /home/a/projects/digit-ml/claimcheck — на площадке
экспериментов, где нет ни версии, ни пакета, а пути к компилятору были вбиты
абсолютными строками в чужие домашние каталоги. Зависеть от такого значит
зависеть от состояния чьей-то рабочей копии, и на вопрос «какой код сказал
пользователю ПРОВЕРЕНО» перестаёт быть ответ.

Компилятор и детектор при этом НЕ копировались и не будут: вторая копия
компилятора — это вторая реализация семантики FTS, а вся затея держится на
том, что она одна. Они остаются внешним процессом (см. bridge.py).

Цена копии названа в NOTICE: расхождение с экспериментом теперь возможно,
синхронизация ручная.

Точка входа
-----------
    from digit_cli import claimcheck

    if not claimcheck.runtime_available():
        ...  # проверять нечем — это отказ, а не зелёный ответ
    result = claimcheck.answer(["если сумма заказа больше 1000, то прибавить 100"],
                               schema, "Продажи")
    result["outcome"]   # "проверено_верно" | "проверено_неверно" | "не_формализовано"
    result["reading"]   # как система ПРОЧИТАЛА утверждение — главное для доверия
    result["note"]      # граница, обязательная во всех трёх исходах
"""

