"""Три слоя портрета и граница между ними — в типах, а не в документации.

Замысел «цифрового портрета» смешивает три разные вещи, и смешивать их
опасно ровно в одну сторону: догадка, положенная рядом с фактом, через день
читается как факт. Поэтому слой — не поле в отчёте, а свойство объекта,
которое нельзя ни выставить, ни переопределить:

``STYLE`` — **как** владелец формулирует. Числа, снятые с его сообщений:
    длина фраз, отличительная лексика, какими словами он отказывает,
    сомневается, соглашается. Проверяется пересчётом на том же корпусе.

``RECORD`` — **что** он решил. Дословная цитата плюс происхождение: сессия,
    время, ход, чем подтверждается. Ничего не перефразировано, поэтому
    запись можно показать третьему лицу: «вы решали так-то, вот ссылка».

``CONJECTURE`` — **что бы он ответил** на новый вопрос. Порождение от чужого
    имени. Наружу не уходит никогда; владельцу показывается только с шапкой.

Граница между вторым и третьим — вся суть. Она держится тремя механизмами:

1. ``origin`` — атрибут класса, а не значение поля. Экземпляр не может
   соврать о своём слое: у :class:`~agent.portrait.decisions.DecisionRecord`
   он всегда ``RECORD``, у :class:`~agent.portrait.conjecture.Conjecture`
   всегда ``CONJECTURE``.
2. :func:`render` отказывается рисовать что-либо без метки слоя.
3. :func:`outward_safe` — единственная дверь наружу, и она пропускает только
   ``RECORD``. Догадка не «фильтруется по флагу», она вызывает исключение:
   молчаливое выбрасывание однажды станет молчаливым пропусканием.
"""

from __future__ import annotations

from enum import Enum
from typing import Iterable, List, Protocol, runtime_checkable


class Origin(str, Enum):
    """Слой происхождения. Ровно три — четвёртого не бывает."""

    STYLE = "style"
    RECORD = "record"
    CONJECTURE = "conjecture"


#: Человекочитаемая метка слоя. Ставится перед КАЖДЫМ отрендеренным куском,
#: включая слой фактов: метка, которая появляется только у догадки, читается
#: как предупреждение и через неделю начинает восприниматься как шум.
LABELS = {
    Origin.STYLE: "СТИЛЬ · измерено",
    Origin.RECORD: "РЕШЕНИЕ · факт со ссылкой",
    Origin.CONJECTURE: "ДОГАДКА · сочинено моделью, не владельцем",
}

#: Слои, которые можно показать кому-то, кроме владельца.
OUTWARD_ALLOWED = frozenset({Origin.RECORD})


class ConjectureLeak(RuntimeError):
    """Догадку попытались отправить наружу.

    Отдельный класс, а не ``ValueError``: это не ошибка ввода, а нарушение
    единственного инварианта, ради которого весь модуль существует. Ловить
    его широким ``except Exception`` и продолжать — значит отменить его.
    """


@runtime_checkable
class Attributable(Protocol):
    """Что угодно, знающее свой слой и умеющее показать себя строкой."""

    origin: Origin

    def as_text(self) -> str:  # pragma: no cover - протокол
        ...


def label(origin: Origin) -> str:
    """Метка слоя. Незнакомый слой — ошибка, а не «прочерк»."""
    try:
        return LABELS[Origin(origin)]
    except (KeyError, ValueError) as exc:
        raise ValueError(f"неизвестный слой портрета: {origin!r}") from exc


def render(item: Attributable) -> str:
    """Отрендерить кусок портрета вместе с меткой его слоя.

    Единственный способ получить текст куска. Прямой вызов ``as_text()``
    возможен, но тогда метку ставит вызывающий — и рано или поздно забудет.
    """
    origin = getattr(item, "origin", None)
    if origin is None:
        raise ValueError(
            f"{type(item).__name__} не объявляет слой портрета; "
            "рисовать кусок без указания происхождения нельзя"
        )
    body = item.as_text()
    return f"[{label(origin)}]\n{body}"


def outward_safe(items: Iterable[Attributable]) -> List[Attributable]:
    """Пропустить наружу только то, что имеет проверяемое происхождение.

    Наружу — это всё, что увидит кто-то кроме владельца: ответ в чате,
    письмо, реплика на созвоне. Туда идут только ``RECORD``: у них есть
    дословная цитата и ссылка на источник, поэтому получатель может
    проверить, а не поверить.

    Стиль тоже не проходит. Он не ложь, но и не содержание: «владелец
    отказывает словом „мимо“» — это про владельца, а не про предмет
    разговора, и адресату оно ничего не сообщает.
    """
    out: List[Attributable] = []
    for item in items:
        origin = getattr(item, "origin", None)
        if origin == Origin.CONJECTURE:
            raise ConjectureLeak(
                "попытка отправить наружу догадку портрета. Догадка — это "
                "текст, сочинённый моделью от имени владельца; показывать "
                "его кому-то, кроме самого владельца, нельзя ни с какой "
                "пометкой. Наружу идут только записи решений (RECORD)."
            )
        if origin in OUTWARD_ALLOWED:
            out.append(item)
    return out
