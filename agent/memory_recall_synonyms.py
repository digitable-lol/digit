def _build_index() -> dict[str, Tuple[str, ...]]:
    """Основа слова → синонимы к нему.

    Ключ — основа, а не само слово: запрос приходит в любой форме
    («бэкапы», «доктора»), и искать по точному написанию значило бы завести
    в словаре по строке на падеж.
    """
    index: dict[str, List[str]] = {}
    for group in GROUPS:
        for word in group:
            index.setdefault(stem(word), []).extend(w for w in group if w != word)
    return {k: tuple(dict.fromkeys(v)) for k, v in index.items()}


_INDEX = _build_index()


def synonyms(terms: Sequence[str]) -> List[str]:
    """Слова-синонимы к терминам запроса. Сами термы сюда не входят.

    Вызывается только после промаха обычного поиска, поэтому исходные термы
    в выдаче не нужны: они уже доказали, что не совпадают ни с чем.
    """
    out: List[str] = []
    seen = {stem(t) for t in terms}
    for term in terms:
        for alt in _INDEX.get(stem(term), ()):
            key = stem(alt)
            if key not in seen:
                seen.add(key)
                out.append(alt)
    return out
